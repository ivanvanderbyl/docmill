// Ported from core/fxcodec/flate/flatemodule_unittest.cpp @ pdfium 0db284a42.
// The six Decode cases are PDFium's own expected values; predictor=0. Encode
// cases are NOT ported as exact bytes (Go's zlib differs); see plan 009 Phase B.
package codec

import (
	"bytes"
	"testing"
)

func TestFlateDecode(t *testing.T) {
	cases := []struct {
		name      string
		in        []byte
		out       []byte
		processed uint32
	}{
		{
			name:      "empty",
			in:        []byte{},
			out:       []byte{},
			processed: 0,
		},
		{
			name:      "not zlib",
			in:        []byte("preposterous nonsense"),
			out:       []byte{},
			processed: 2,
		},
		{
			name:      "zlib empty",
			in:        []byte{0x78, 0x9c, 0x03, 0x00, 0x00, 0x00, 0x00, 0x01},
			out:       []byte{},
			processed: 8,
		},
		{
			name:      "single space",
			in:        []byte{0x78, 0x9c, 0x53, 0x00, 0x00, 0x00, 0x21, 0x00, 0x21},
			out:       []byte(" "),
			processed: 9,
		},
		{
			name:      "123",
			in:        []byte{0x78, 0x9c, 0x33, 0x34, 0x32, 0x06, 0x00, 0x01, 0x2d, 0x00, 0x97},
			out:       []byte("123"),
			processed: 11,
		},
		{
			name:      "zero ff",
			in:        []byte{0x78, 0x9c, 0x63, 0xf8, 0x0f, 0x00, 0x01, 0x01, 0x01, 0x00},
			out:       []byte{0x00, 0xff},
			processed: 10,
		},
		{
			name: "content stream",
			in: []byte{
				0x78, 0x9C, 0x33, 0x54, 0x30, 0x00, 0x42, 0x5D, 0x43, 0x05, 0x23, 0x4B, 0x05, 0x73, 0x33, 0x63,
				0x85, 0xE4, 0x5C, 0x2E, 0x90, 0x80, 0xA9, 0xA9, 0xA9, 0x82, 0xB9, 0xB1, 0xA9, 0x42, 0x51, 0x2A,
				0x57, 0xB8, 0x42, 0x1E, 0x57, 0x21, 0x92, 0xA0, 0x89, 0x9E, 0xB1, 0xA5, 0x09, 0x92, 0x84, 0x9E,
				0x85, 0x81, 0x81, 0x25, 0xD8, 0x14, 0x24, 0x26, 0xD0, 0x18, 0x43, 0x05, 0x10, 0x0C, 0x72, 0x57,
				0x80, 0x30, 0x8A, 0xD2, 0xB9, 0xF4, 0xDD, 0x0D, 0x14, 0xD2, 0x8B, 0xC1, 0x46, 0x99, 0x59, 0x1A,
				0x2B, 0x58, 0x1A, 0x9A, 0x83, 0x8C, 0x49, 0xE3, 0x0A, 0x04, 0x42, 0x00, 0x37, 0x4C, 0x1B, 0x42,
			},
			out: []byte("1 0 0 -1 29 763 cm\n0 0 555 735 re\nW n\nq\n0 0 555 734.394 re\n" +
				"W n\nq\n0.8009 0 0 0.8009 0 0 cm\n1 1 1 RG 1 1 1 rg\n/G0 gs\n" +
				"0 0 693 917 re\nf\nQ\nQ\n"),
			processed: 96,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			data, consumed := FlateOrLZWDecode(false, tc.in, false, 0, 0, 0, 0, 0)
			if !bytes.Equal(data, tc.out) {
				t.Errorf("data = %q (%d bytes), want %q (%d bytes)", data, len(data), tc.out, len(tc.out))
			}
			if consumed != tc.processed {
				t.Errorf("bytesConsumed = %d, want %d", consumed, tc.processed)
			}
		})
	}
}
